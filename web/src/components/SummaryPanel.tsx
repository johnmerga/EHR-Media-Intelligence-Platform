import type { ClinicalSummary } from "../api/types";
import { formatDate } from "../lib/format";
import { ConfidenceBadge } from "./Badges";

const HEADING = "text-xs font-semibold uppercase tracking-wide text-slate-500";

function BulletList({ items, empty }: { items: string[]; empty: string }) {
  if (items.length === 0) return <p className="mt-1 text-sm text-slate-500">{empty}</p>;
  return (
    <ul className="mt-1 list-disc space-y-0.5 pl-5 text-sm text-slate-800">
      {items.map((item) => (
        <li key={item}>{item}</li>
      ))}
    </ul>
  );
}

export function SummaryPanel({ summary }: { summary: ClinicalSummary | null }) {
  if (summary === null) {
    return <p className="text-sm text-slate-600">No summary has been generated for this patient.</p>;
  }
  const isAi = summary.generator === "llm";

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-2">
        <span className="inline-flex items-center rounded-full bg-slate-100 px-2 py-0.5 text-xs font-medium text-slate-700 ring-1 ring-inset ring-slate-200">
          {isAi ? "AI-generated" : "Rule-based extract (not AI)"}
        </span>
        <ConfidenceBadge level={summary.confidence} />
      </div>

      <div>
        <h4 className={HEADING}>Chief concern</h4>
        <p className="mt-1 text-sm text-slate-800">{summary.chief_concern}</p>
      </div>

      <div>
        <h4 className={HEADING}>Key diagnoses</h4>
        <BulletList items={summary.key_diagnoses} empty="None documented." />
      </div>

      <div>
        <h4 className={HEADING}>Recent media records</h4>
        {summary.recent_media_records.length === 0 ? (
          <p className="mt-1 text-sm text-slate-500">No imaging or laboratory records.</p>
        ) : (
          <ul className="mt-1 divide-y divide-slate-100 text-sm">
            {summary.recent_media_records.map((record) => (
              <li key={`${record.date}-${record.type}`} className="py-1.5">
                <span className="font-medium text-slate-800">{record.type}</span>
                <span className="text-slate-500"> · {formatDate(record.date === "undated" ? null : record.date)}</span>
                <p className="text-slate-700">{record.finding}</p>
              </li>
            ))}
          </ul>
        )}
      </div>

      <div>
        <h4 className={HEADING}>Flagged anomalies</h4>
        <BulletList items={summary.flagged_anomalies} empty="None flagged." />
      </div>

      <p
        role="note"
        className="rounded-md border border-amber-200 bg-amber-50 px-3 py-2 text-xs leading-relaxed text-amber-900"
      >
        <span className="font-semibold">Disclaimer: </span>
        {summary.disclaimer}
      </p>
      <p className="text-xs text-slate-500">
        Generated by <span className="font-mono">{summary.model}</span> on{" "}
        {formatDate(summary.generated_at)}.
      </p>
    </div>
  );
}
